#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
CCOS WRKOPS 1.8.2 — wrksettings (deterministic settings composition)
=====================================================================
The pure composition/validation layer behind the deployment manifest's
`settings_compose` projection (`.claude/settings.json`). B4 declared that
projection and said, in its own words, that composition was "declared only in
B4; not implemented until B5". This module is that implementation.

What this module is
-------------------
A PURE library. It composes `settings.base.json` with exactly one stack
variant, resolves the runtime env values its caller hands it, validates the
result fail-closed, and renders deterministic UTF-8 bytes.

What this module is NOT
-----------------------
It is not a deployer. There is deliberately no function here that writes a
real project's `.claude/settings.json` — actual deployment mutation is later
work, and a composer that can also write is a composer that can deploy by
accident. A caller such as a future `wrkdeploy` supplies the selected source
data, the workspace root, the interpreter path, the deployment manifest and
the settings schema; it owns the write.

Why the composition laws look the way they do
---------------------------------------------
  - Base is authoritative for hooks. A variant may ADD hook groups; it may
    not delete, replace, reorder or empty an inherited one. A stack variant
    that could silently drop `block_git.py` would turn a boundary law into a
    suggestion, so an explicit attempt to empty an inherited hook event is a
    hard error rather than a quiet no-op.
  - Permission rule arrays are stable unions, never sorted. Claude Code reads
    every array entry as a literal rule, and base order encodes the
    documented rule map recorded in settings.base.json's own notes
    (deny[0:23] NO_INSTALL, deny[23:43] NO_RUNTIME, ...). Sorting would
    destroy that map without changing a single rule's meaning, which is the
    worst kind of silent damage.
  - Every source key beginning with `//` is a comment and is stripped. The
    output receives exactly one generated `//` key. Source comments are
    authored for editors of the source; they are noise (and, in 1.8.1c's
    experience, active confusion) in a generated artefact.
  - Hook wiring is validated against the DEPLOYMENT_MANIFEST, bidirectionally,
    and the event names are DERIVED from the manifest and the base layer —
    never hardcoded as a count. The archive previously carried a stale "4
    events" claim against a baseline of 3 event names / 4 matcher groups /
    5 hook commands. A number written in prose cannot verify anything; a
    manifest-driven check can.
  - Env values must arrive already resolved. `$CLAUDE_PROJECT_DIR`, relative
    paths and the legacy workstation interpreter are rejected outright.
    Whether a resolved path EXISTS is not this layer's question — resolution
    and existence authority belong to the caller.

Dependency law: standard library only, plus `wrkparse` for schema validation.
CLAUDECLI.2.02 NO_INSTALL forbids pip dependencies in shipped code, so
`settings.schema.json` is written in the documented Draft 2020-12 subset
`wrkparse.validate_against_schema` actually implements. Semantic rules that
subset cannot express (hook wiring, env resolution, comment-key discipline)
stay here as explicit fail-closed checks.
"""
