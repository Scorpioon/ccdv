# --- frozen output contract -------------------------------------------------

# The single generated comment key the composed artefact carries. Exact text;
# the operator-local escape hatch is named here because a generated file with
# no stated escape hatch gets hand-edited, and then regenerated over.
GENERATED_COMMENT_KEY = "//"
GENERATED_COMMENT_VALUE = (
    "Generated by WRKOPS wrksettings; use .claude/settings.local.json "
    "for operator-local overrides.")

COMMENT_PREFIX = "//"

# Final top-level contract for 1.8.2. All four are required, nothing else is
# accepted. `settings.local.json` is NOT an input to composition and never
# appears as a source layer.
TOP_LEVEL_KEYS = ("//", "permissions", "hooks", "env")

# Permission rule arrays governed by the stable-union law.
PERMISSION_LISTS = ("deny", "allow")

# Minimum CCOS env baseline the composed artefact must carry. Extra valid env
# keys are allowed; these eleven are not optional.
REQUIRED_ENV_KEYS = (
    "CCOS_ACTIVE_TASK",
    "CCOS_ALLOW_READONLY_GIT",
    "CCOS_HANDOFF_DIR",
    "CCOS_INTEL_DIR",
    "CCOS_METADATA_DIR",
    "CCOS_OPS_ROOT",
    "CCOS_PYTHON",
    "CCOS_REPORT_DIR",
    "CCOS_REPORT_STRICT",
    "CCOS_WORKSPACE_ROOT",
    "CCOS_WRKOPS_DIR",
)

WORKSPACE_ROOT_ENV_KEY = "CCOS_WORKSPACE_ROOT"
PYTHON_ENV_KEY = "CCOS_PYTHON"

# Manifest role that must be wired by exactly one settings hook command.
HOOK_ENTRYPOINT_ROLE = "hook_entrypoint"

# The deployed hook-target shape a composed hook command may invoke. Matched
# as a whole path, never searched as a substring.
HOOK_TARGET_RE = re.compile(r"^\.claude/hooks/[^/]+\.py$")

# Deployment-root variables a wired hook command may prefix its path with.
# Same set the B4 release-consistency verifier recognises.
_DEPLOY_ROOT_PREFIXES = (
    "$CLAUDE_PROJECT_DIR/",
    "${CLAUDE_PROJECT_DIR}/",
    "%CLAUDE_PROJECT_DIR%/",
)

# double-quoted | single-quoted | bare token of a hook command string
_COMMAND_TOKEN_RE = re.compile(r"""
      "([^"]*)"        # double-quoted token
    | '([^']*)'        # single-quoted token
    | (\S+)            # bare token
""", re.VERBOSE)

# Any $VAR / ${VAR} / %VAR% shaped token left in a value that was supposed to
# be resolved. A resolved value is a value with no variables left in it.
_PLACEHOLDER_RE = re.compile(r"\$\{?[A-Za-z_][A-Za-z0-9_]*\}?"
                             r"|%[A-Za-z_][A-Za-z0-9_]*%")

# Drive-qualified absolute path (C:\..., K:/...).
_DRIVE_ABS_RE = re.compile(r"^[A-Za-z]:[\\/]")

_PROJECT_DIR_TOKENS = (
    "$CLAUDE_PROJECT_DIR",
    "${CLAUDE_PROJECT_DIR}",
    "%CLAUDE_PROJECT_DIR%",
)

# The machine-specific interpreter that leaked into settings.python.json, in
# both its plain and its over-escaped spelling. Backslash-normalised and
# case-folded before comparison, so `K:/PYTHON/python.exe` is caught too.
LEGACY_PYTHON_VALUES = frozenset({
    "k:\\python\\python.exe",
    "k:\\\\python\\\\python.exe",
})


class SettingsError(Exception):
    """Raised when composition cannot proceed or the result is not valid.

    Fail-closed: every rejection path raises or reports. Nothing here returns
    a partially composed artefact.
    """


# --- comment-key discipline -------------------------------------------------

def strip_comment_keys(value):
    """Return `value` with every `//`-prefixed mapping key removed, recursively.

    Applied to SOURCE layers before merge. The generated `//` key is added
    afterwards, so the result carries exactly one and it is ours.
    """
    if isinstance(value, dict):
        return {k: strip_comment_keys(v) for k, v in value.items()
                if not (isinstance(k, str) and k.startswith(COMMENT_PREFIX))}
    if isinstance(value, list):
        return [strip_comment_keys(v) for v in value]
    return value


def comment_key_paths(value, path=""):
    """Dotted paths of every `//`-prefixed key found BELOW the top level.

    The top-level generated key is the one legal comment key, so it is not
    reported here; `validate_composed` checks it separately.
    """
    found = []
    if isinstance(value, dict):
        for key in sorted(value, key=str):
            child = f"{path}.{key}" if path else str(key)
            if path and isinstance(key, str) and key.startswith(COMMENT_PREFIX):
                found.append(child)
            found += comment_key_paths(value[key], child)
    elif isinstance(value, list):
        for i, item in enumerate(value):
            found += comment_key_paths(item, f"{path}[{i}]")
    return found


# --- merge laws -------------------------------------------------------------

def _canonical(value):
    """Stable canonical text for structural comparison/de-duplication."""
    return json.dumps(value, sort_keys=True, ensure_ascii=False,
                      separators=(",", ":"))


def merge_permission_rules(base_rules, variant_rules):
    """Stable union of two permission rule arrays.

    Base order is preserved, variant-only rules are appended in variant order,
    exact duplicates are dropped. The array is never sorted.
    """
    if not isinstance(base_rules, list) or not isinstance(variant_rules, list):
        raise SettingsError("permission rule arrays must be lists")
    merged = []
    seen = set()
    for rule in list(base_rules) + list(variant_rules):
        key = _canonical(rule)
        if key in seen:
            continue
        seen.add(key)
        merged.append(copy.deepcopy(rule))
    return merged


def merge_hooks(base_hooks, variant_hooks):
    """Merge hook maps under the base-is-authoritative law.

    Inherited base groups survive unchanged and in order. A variant may append
    groups (deduplicated structurally) and may introduce entirely new events.
    A variant may not delete, replace or empty an inherited event.
    """
    if not isinstance(base_hooks, dict):
        raise SettingsError("base 'hooks' must be an object")
    if not isinstance(variant_hooks, dict):
        raise SettingsError("variant 'hooks' must be an object")

    merged = {}
    for event, groups in base_hooks.items():
        if not isinstance(groups, list):
            raise SettingsError(
                f"base hooks[{event!r}] must be a list of hook groups")
        merged[event] = [copy.deepcopy(g) for g in groups]

    for event, groups in variant_hooks.items():
        if not isinstance(groups, list):
            raise SettingsError(
                f"variant hooks[{event!r}] must be a list of hook groups")
        inherited = merged.get(event)
        if inherited is None:
            merged[event] = [copy.deepcopy(g) for g in groups]
            continue
        if inherited and not groups:
            # An explicit empty overlay on an inherited event is the exact
            # shape of "quietly disable the guard". It fails closed.
            raise SettingsError(
                f"variant may not empty inherited hook event {event!r} "
                f"(base declares {len(inherited)} group(s))")
        seen = {_canonical(g) for g in inherited}
        for group in groups:
            key = _canonical(group)
            if key in seen:
                continue
            seen.add(key)
            inherited.append(copy.deepcopy(group))

    return merged


def deep_merge(base, variant, path=()):
    """Recursive deep merge; `variant` overlays `base`.

    Objects merge recursively. `permissions.deny` / `permissions.allow` take
    the stable-union law, `hooks` takes the base-authoritative law, every
    other list and every scalar is variant-wins.
    """
    if not isinstance(base, dict) or not isinstance(variant, dict):
        return copy.deepcopy(variant)

    merged = {key: copy.deepcopy(value) for key, value in base.items()}

    for key, v_val in variant.items():
        here = path + (key,)
        if key not in merged:
            merged[key] = copy.deepcopy(v_val)
            continue
        b_val = merged[key]
        if here == ("hooks",):
            merged[key] = merge_hooks(b_val, v_val)
        elif (len(here) == 2 and here[0] == "permissions"
                and here[1] in PERMISSION_LISTS):
            merged[key] = merge_permission_rules(b_val, v_val)
        elif isinstance(b_val, dict) and isinstance(v_val, dict):
            merged[key] = deep_merge(b_val, v_val, here)
        else:
            merged[key] = copy.deepcopy(v_val)

    return merged


# --- env resolution ---------------------------------------------------------

def _is_absolute_path(value):
    """True for POSIX absolute, UNC, or drive-qualified paths."""
    if not isinstance(value, str) or not value:
        return False
    if _DRIVE_ABS_RE.match(value):
        return True
    return value.replace("\\", "/").startswith("/")


def _reject_runtime_value(key, value):
    """Error string if this resolved runtime value is not acceptable, else None.

    Caller guarantees `value` is a non-empty string.
    """
    for token in _PROJECT_DIR_TOKENS:
        if token in value:
            return (f"{key}: {token} is a deployment-time variable, not a "
                    f"resolved value")
    if _PLACEHOLDER_RE.search(value):
        return f"{key}: unresolved placeholder token in {value!r}"
    if not _is_absolute_path(value):
        return f"{key}: resolved value must be an absolute path, got {value!r}"
    return None


def _reject_legacy_python(value):
    """Error string if `value` is the legacy workstation interpreter, else None."""
    if value.replace("/", "\\").casefold() in LEGACY_PYTHON_VALUES:
        return (f"{PYTHON_ENV_KEY}: {value!r} is the legacy workstation "
                f"interpreter value and must not be materialised")
    return None


def validate_runtime_env(env):
    """Return a list of errors for the composed `env` block; empty == valid."""
    errors = []
    if not isinstance(env, dict):
        return ["env: must be an object"]

    for key in sorted(env, key=str):
        value = env[key]
        if not isinstance(value, str):
            errors.append(f"env.{key}: value must be a string, got "
                          f"{type(value).__name__}")
        elif not value.strip():
            errors.append(f"env.{key}: value must be a non-empty string")

    for key in REQUIRED_ENV_KEYS:
        if key not in env:
            errors.append(f"env.{key}: required CCOS env key missing")

    for key in (WORKSPACE_ROOT_ENV_KEY, PYTHON_ENV_KEY):
        value = env.get(key)
        if not isinstance(value, str) or not value.strip():
            continue  # already reported above
        err = _reject_runtime_value(key, value)
        if err:
            errors.append("env." + err)

    value = env.get(PYTHON_ENV_KEY)
    if isinstance(value, str) and value.strip():
        err = _reject_legacy_python(value)
        if err:
            errors.append("env." + err)

    return errors


def resolve_env(env, workspace_root, python_path):
    """Overwrite source env defaults with the caller's resolved runtime values.

    The source layers ship safe-generic defaults (`python`,
    `$CLAUDE_PROJECT_DIR`). Those are inputs to authoring, never outputs of
    composition: the materialised artefact must carry real absolute values.
    """
    if not isinstance(env, dict):
        raise SettingsError("'env' must be an object")
    resolved = {key: copy.deepcopy(value) for key, value in env.items()}
    resolved[WORKSPACE_ROOT_ENV_KEY] = workspace_root
    resolved[PYTHON_ENV_KEY] = python_path
    errors = validate_runtime_env(resolved)
    if errors:
        raise SettingsError("env resolution rejected: " + "; ".join(errors))
    return resolved


# --- hook consistency law ---------------------------------------------------

def command_target_paths(command):
    """Deployment-root-relative paths a hook command string actually invokes.

    Tokens are unquoted and stripped of the deployment-root variable prefixes
    settings.base.json uses, so the result is compared to a manifest `target`
    as a PATH. A substring search would let a prose mention of the same
    basename count as wiring.
    """
    paths = set()
    if not isinstance(command, str):
        return paths
    for match in _COMMAND_TOKEN_RE.finditer(command):
        token = next((g for g in match.groups() if g is not None), None)
        if not token:
            continue
        norm = token.replace("\\", "/")
        for prefix in _DEPLOY_ROOT_PREFIXES:
            if norm.startswith(prefix):
                norm = norm[len(prefix):]
                break
        else:
            if norm.startswith("./"):
                norm = norm[2:]
        if norm:
            paths.add(norm)
    return paths


def collect_wired_hook_targets(hooks):
    """`{deployed hook path: [event, ...]}` for every wired hook command.

    Only `"type": "command"` handlers contribute wiring; matcher strings and
    other handler shapes are configuration prose, not an invocation. One entry
    is appended per invocation, so a path wired twice reports twice.
    """
    wired = {}
    if not isinstance(hooks, dict):
        return wired
    for event in sorted(hooks, key=str):
        groups = hooks.get(event)
        if not isinstance(groups, list):
            continue
        for group in groups:
            if not isinstance(group, dict):
                continue
            handlers = group.get("hooks")
            if not isinstance(handlers, list):
                continue
            for handler in handlers:
                if not isinstance(handler, dict):
                    continue
                if handler.get("type") != "command":
                    continue
                for target in sorted(command_target_paths(handler.get("command"))):
                    if HOOK_TARGET_RE.match(target):
                        wired.setdefault(target, []).append(event)
    return wired


def manifest_hook_entrypoints(manifest):
    """`[(id, target, hook_event)]` for every manifest hook_entrypoint projection."""
    if not isinstance(manifest, dict):
        raise SettingsError("deployment manifest must be a JSON object")
    projections = manifest.get("projections")
    if not isinstance(projections, list):
        raise SettingsError("deployment manifest 'projections' must be a list")
    entrypoints = []
    for entry in projections:
        if not isinstance(entry, dict):
            continue
        if entry.get("role") != HOOK_ENTRYPOINT_ROLE:
            continue
        entrypoints.append((entry.get("id"), entry.get("target"),
                            entry.get("hook_event")))
    return entrypoints


def validate_hook_consistency(composed, manifest):
    """Bidirectional, manifest-driven hook wiring check.

    Forward: every `hook_entrypoint` projection is wired by exactly one
    settings hook command, under the event the manifest declares.
    Reverse: every composed hook command invoking a deployed hook path
    resolves to a declared `hook_entrypoint` target.

    `hook_support` projections (hookpath.py) are not required to be wired.
    """
    errors = []
    hooks = composed.get("hooks") if isinstance(composed, dict) else None
    if not isinstance(hooks, dict):
        return ["hooks: composed settings must declare an object 'hooks'"]

    wired = collect_wired_hook_targets(hooks)

    declared = {}
    for pid, target, event in manifest_hook_entrypoints(manifest):
        if not isinstance(target, str) or not isinstance(event, str):
            errors.append(f"manifest {pid!r}: hook_entrypoint must declare a "
                          f"string 'target' and 'hook_event'")
            continue
        norm = target.replace("\\", "/")
        if norm in declared:
            errors.append(f"manifest {pid!r}: duplicate hook_entrypoint target "
                          f"{norm!r}")
            continue
        declared[norm] = (pid, event)

    for target in sorted(declared):
        pid, event = declared[target]
        events = wired.get(target, [])
        if not events:
            errors.append(f"hooks: manifest hook_entrypoint {pid!r} target "
                          f"{target!r} is not wired by any settings hook command")
        elif len(events) > 1:
            errors.append(f"hooks: manifest hook_entrypoint {pid!r} target "
                          f"{target!r} is wired {len(events)} times under "
                          f"{sorted(events)}; exactly one is required")
        elif events[0] != event:
            errors.append(f"hooks: manifest hook_entrypoint {pid!r} target "
                          f"{target!r} is wired under event {events[0]!r}, "
                          f"manifest declares {event!r}")

    for target in sorted(wired):
        if target not in declared:
            errors.append(f"hooks: settings wires {target!r}, which is not a "
                          f"declared deployment-manifest hook_entrypoint target")

    return errors


def validate_inherited_hooks(base, composed):
    """Every base hook group must survive composition, unchanged and in order."""
    errors = []
    base_hooks = base.get("hooks") if isinstance(base, dict) else None
    composed_hooks = composed.get("hooks") if isinstance(composed, dict) else None
    if not isinstance(base_hooks, dict):
        return ["base hooks: must be an object"]
    if not isinstance(composed_hooks, dict):
        return ["hooks: composed settings must declare an object 'hooks'"]

    for event in sorted(base_hooks, key=str):
        expected = base_hooks.get(event)
        if not isinstance(expected, list):
            errors.append(f"base hooks.{event}: must be a list of hook groups")
            continue
        actual = composed_hooks.get(event)
        if not isinstance(actual, list):
            errors.append(f"hooks.{event}: inherited base hook event is missing "
                          f"from the composed settings")
            continue
        want = [_canonical(strip_comment_keys(g)) for g in expected]
        have = [_canonical(g) for g in actual]
        cursor = 0
        for key in want:
            try:
                cursor = have.index(key, cursor) + 1
            except ValueError:
                errors.append(
                    f"hooks.{event}: an inherited base hook group was removed, "
                    f"altered, or reordered")
                break

    return errors


# --- permissions ------------------------------------------------------------

def validate_permissions(permissions):
    """Return a list of errors for the composed `permissions` block."""
    errors = []
    if not isinstance(permissions, dict):
        return ["permissions: must be an object"]
    for name in PERMISSION_LISTS:
        rules = permissions.get(name)
        if not isinstance(rules, list) or not rules:
            errors.append(f"permissions.{name}: must be a non-empty list of "
                          f"rule strings")
            continue
        seen = set()
        for i, rule in enumerate(rules):
            if not isinstance(rule, str) or not rule.strip():
                errors.append(f"permissions.{name}[{i}]: rule must be a "
                              f"non-empty string")
                continue
            if rule in seen:
                errors.append(f"permissions.{name}[{i}]: duplicate rule "
                              f"{rule!r} survived the stable union")
            seen.add(rule)
    extra = [k for k in sorted(permissions, key=str)
             if k not in PERMISSION_LISTS]
    if extra:
        errors.append(f"permissions: unexpected key(s) {extra}; the frozen "
                      f"1.8.2 contract is deny + allow")
    return errors


# --- schema -----------------------------------------------------------------

def load_settings_schema(schema_dir):
    """Load `settings.schema.json` through the shared wrkparse loader."""
    return wrkparse.load_schema(schema_dir, "settings")


def validate_with_schema(composed, schema):
    """Validate the composed object against the supported schema subset.

    Delegates to `wrkparse.validate_against_schema`, which reports an
    unsupported schema keyword as an error rather than skipping it — a
    validator that silently ignores a rule proves nothing.
    """
    return list(wrkparse.validate_against_schema(composed, schema))


# --- top-level validation ---------------------------------------------------

def validate_composed(composed, base=None, manifest=None, schema=None):
    """Validate a composed settings object. Returns errors; empty == valid.

    `base`, `manifest` and `schema` are optional authorities: each one that is
    supplied adds its own layer of checking. None of them is inferred.
    """
    if not isinstance(composed, dict):
        return ["composed settings must be a JSON object"]

    errors = []

    comment_keys = sorted(k for k in composed
                          if isinstance(k, str) and k.startswith(COMMENT_PREFIX))
    if comment_keys != [GENERATED_COMMENT_KEY]:
        errors.append(f"top level must carry exactly one generated "
                      f"{GENERATED_COMMENT_KEY!r} key, found {comment_keys}")
    elif composed[GENERATED_COMMENT_KEY] != GENERATED_COMMENT_VALUE:
        errors.append(f"{GENERATED_COMMENT_KEY!r} does not carry the frozen "
                      f"generated value")

    residue = comment_key_paths(composed)
    if residue:
        errors.append(f"source comment key(s) survived composition: {residue}")

    missing = [k for k in TOP_LEVEL_KEYS if k not in composed]
    if missing:
        errors.append(f"missing required top-level key(s): {missing}")
    extra = [k for k in sorted(composed, key=str) if k not in TOP_LEVEL_KEYS]
    if extra:
        errors.append(f"unexpected top-level key(s): {extra}")

    errors += validate_permissions(composed.get("permissions"))
    errors += validate_runtime_env(composed.get("env"))

    if base is not None:
        errors += validate_inherited_hooks(base, composed)
    if manifest is not None:
        errors += validate_hook_consistency(composed, manifest)
    if schema is not None:
        errors += validate_with_schema(composed, schema)

    return errors


# --- deterministic rendering ------------------------------------------------

def render(composed):
    """Render composed settings to deterministic bytes.

    UTF-8, no BOM, LF line endings, two-space indentation, keys sorted, array
    order left exactly as the merge laws produced it, exactly one final LF.
    Two renders of identical semantic input are byte-identical.
    """
    text = json.dumps(composed, indent=2, sort_keys=True, ensure_ascii=False,
                      separators=(",", ": "))
    return (text + "\n").encode("utf-8")


# --- composition pipeline ---------------------------------------------------

def compose(base, variant, workspace_root, python_path,
            manifest=None, schema=None):
    """Compose base + one variant into a validated settings object.

    `workspace_root` and `python_path` are the caller's RESOLVED absolute
    values. Raises SettingsError on any rejection; never returns a partially
    composed or unvalidated artefact.
    """
    if not isinstance(base, dict):
        raise SettingsError("base settings must be a JSON object")
    if not isinstance(variant, dict):
        raise SettingsError("variant settings must be a JSON object")

    clean_base = strip_comment_keys(base)
    clean_variant = strip_comment_keys(variant)

    composed = deep_merge(clean_base, clean_variant)
    composed["env"] = resolve_env(composed.get("env", {}),
                                  workspace_root, python_path)
    composed[GENERATED_COMMENT_KEY] = GENERATED_COMMENT_VALUE

    errors = validate_composed(composed, base=clean_base, manifest=manifest,
                               schema=schema)
    if errors:
        raise SettingsError("composed settings rejected: " + "; ".join(errors))
    return composed


def compose_bytes(base, variant, workspace_root, python_path,
                  manifest=None, schema=None):
    """`compose` + `render`. Returns the deterministic UTF-8 bytes only.

    This is as close to deployment as B5 goes: bytes in memory, handed back to
    a caller that owns the write.
    """
    return render(compose(base, variant, workspace_root, python_path,
                          manifest=manifest, schema=schema))


# --- read-only source loading -----------------------------------------------

def load_json(path):
    """Read one UTF-8 JSON document, strictly.

    Encoding is strict for the same reason wrkparse's is: a source we cannot
    decode is a source we cannot trust, and `errors='replace'` would compose
    corruption into a deployed artefact.
    """
    p = Path(path)
    if not p.is_file():
        raise SettingsError(f"file not found: {path}")
    try:
        text = p.read_text(encoding="utf-8")
    except UnicodeDecodeError as exc:
        raise SettingsError(f"{path} is not valid UTF-8: {exc}")
    except OSError as exc:
        raise SettingsError(f"cannot read {path}: {exc}")
    try:
        return json.loads(text)
    except json.JSONDecodeError as exc:
        raise SettingsError(f"{path} is not valid JSON: {exc}")
